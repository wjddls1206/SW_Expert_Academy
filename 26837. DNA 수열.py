TC = int(input())

for tc in range(TC):
    N, S = input().split()
    N = int(N)

    result = 0

    # (A-T, C-G) 상태별 등장 횟수
    count = {(0, 0): 1}

    diff_AT = 0
    diff_CG = 0

    for ch in S:
        if ch == 'A':
            diff_AT += 1
        elif ch == 'T':
            diff_AT -= 1
        elif ch == 'C':
            diff_CG += 1
        elif ch == 'G':
            diff_CG -= 1

        state = (diff_AT, diff_CG)

        if state in count:
            result += count[state]      
            # 그 과거 위치들을 시작점으로 만들 수 있는 조건 만족 부분 문자열을 전부 추가한다.
            # 누적 상태를 이용해 정답을 누적하는 부분
            count[state] += 1
        else:
            count[state] = 1
            # 이 상태가 과거에 몇 번 있었는가

    print(result)

# 시도 1 (미해결)
# 입력받은 문자열을 S[i]부터 S[j]까지 슬라이싱 해 tmp_S에 저장
# tmp_S에서 A, T, G, C의 개수 count
# A의 개수 = T의 개수 and G의 개수 = C의 개수
# 일 때 result += 1
#
# 이 방법은 문자열을 입력받고 슬라이싱하면서
# 즉, i와 j를 바꿔주기 위해
# 시간복잡도가 O(N^2)가 돼서 시간 초과가 발생함.


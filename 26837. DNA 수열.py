# 시간복잡도를 O(N^2)에서 O(N)으로 줄이기 위해
# list가 아닌 dictionary를 사용.
# 자료구조만을 바꾼 것이 아닌 알고리즘 자체를 변경.
# A와 T, G와 C의 개수가 같아야 함을 이용한 것은 동일.
# A와 G가 등장하면 각각 A-T, G-C에 +1
# T와 C가 등장하면 각각 A-T, G-C에 -1
# dictionary에 (A의 개수 - T의 개수, G의 개수 - C의 개수) 의 순서쌍으로 state를 생성
# 만약 state가 딕셔너리 count에 존재할 경우 result에 count(state)으로 딕셔너리의 값을 불러와 더함
# 이후 딕셔너리의 키가 (0,0) 인 값에 +1
# state가 딕셔너리 count에 존재하지 않을 경우
# 딕셔너리의 키가 state 인 값을 1로 만들어 딕셔너리에 추가

